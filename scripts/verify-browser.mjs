import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const baseURL = process.env.PREVIEW_URL || 'http://127.0.0.1:5193';
const out = new URL('../.tmp/browser/', import.meta.url);
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true, args: ['--mute-audio'] });
const page = await browser.newPage({ viewport: { width: 960, height: 1120 } });
const errors = [];
const workers = [];
page.on('pageerror', error => errors.push(error.message));
page.on('worker', worker => workers.push(worker.url()));
const state = () => page.locator('#verification-state').textContent().then(JSON.parse);
const ready = () => page.waitForFunction(() => !document.querySelector('#write').disabled, undefined, { timeout: 15000 });
try {
  await page.goto(baseURL);
  await ready();
  assert.equal((await state()).title, '小星星');
  assert.equal((await state()).worker, true);
  assert.ok(workers.some(url => url.includes('score.worker')));
  await page.screenshot({ path: new URL('verify-browser__comparison.png', out).pathname.slice(1), fullPage: true });
  for (const candidate of ['a', 'b']) await page.locator(`[data-candidate="${candidate}"]`).screenshot({ path: new URL(`verify-browser__candidate-${candidate}.png`, out).pathname.slice(1) });
  await page.locator('.format-lab summary').click();
  const before = (await state()).score;
  await page.getByRole('button', { name: '写回并重读' }).click();
  await ready();
  assert.deepEqual((await state()).score, before);
  assert.equal((await state()).exportWorker, true);
  const fixture = String.raw`\title "输入验证" \tempo 76 \tuning (D4 A3 F3 C3 G2 D2) \ts (4 4)
(0.1 12.2).4{d} (0.1{t} 12.2{t}).8 r.4 7.6.4 |`;
  await page.locator('#source').fill(fixture);
  await page.getByRole('button', { name: '载入曲谱' }).click();
  await ready();
  const edited = (await state()).score;
  assert.equal(edited.title, '输入验证');
  assert.equal(edited.bars[0].beats[0].notes[1].fret, 12);
  await page.getByRole('button', { name: '写回并重读' }).click();
  await ready();
  assert.deepEqual((await state()).score, edited);
  const bad = String.raw`\title "错误输入" 0.1{b (0 4)}.1`;
  await page.locator('#source').fill(bad);
  await page.getByRole('button', { name: '载入曲谱' }).click();
  await page.waitForFunction(() => document.querySelector('#result').value.includes('尚未支持'));
  assert.equal(await page.locator('#source').inputValue(), bad);
  assert.equal(await page.locator('#write').isDisabled(), true);
  await page.locator('#source').fill(fixture);
  await page.getByRole('button', { name: '重试计算' }).click();
  await ready();
  assert.equal((await state()).score.title, '输入验证');
  const taskAudit = await page.evaluate(async () => {
    const { ScoreWorkerClient } = await import('/src/workers/client.ts');
    const client = new ScoreWorkerClient();
    client.setVersion(1);
    const stale = client.request({ kind: 'parse', text: String.raw`\title "旧曲谱" 0.1.1` }).catch(error => error.name);
    client.setVersion(2);
    const fresh = await client.request({ kind: 'parse', text: String.raw`\title "最新曲谱" 3.1.1` });
    const staleName = await stale;
    const result = { staleName, freshTitle: fresh.result.title, version: fresh.version, worker: fresh.worker };
    client.dispose();
    return result;
  });
  assert.deepEqual(taskAudit, { staleName: 'StaleTaskError', freshTitle: '最新曲谱', version: 2, worker: true });
  const longText = String.raw`\title "长谱测试" \ts (4 4) ` + '0.1.8 1.1.8 2.1.8 3.1.8 4.1.8 5.1.8 6.1.8 7.1.8 | '.repeat(200);
  const longAudit = await page.evaluate(async text => {
    const { ScoreWorkerClient } = await import('/src/workers/client.ts');
    const client = new ScoreWorkerClient();
    let frames = 0;
    const frame = () => { frames++; frameId = requestAnimationFrame(frame); };
    let frameId = requestAnimationFrame(frame);
    const start = performance.now();
    const parsed = await client.request({ kind: 'parse', text });
    const { CANDIDATES } = await import('/src/settings/display.ts');
    const layout = await client.request({ kind: 'layout', score: parsed.result, width: 340, settings: CANDIDATES.b });
    cancelAnimationFrame(frameId);
    const audit = { bars: parsed.result.bars.length, layouts: layout.result.length, parseMs: parsed.elapsedMs, layoutMs: layout.elapsedMs, elapsedMs: performance.now() - start, frames };
    client.dispose();
    return audit;
  }, longText);
  assert.equal(longAudit.bars, 200);
  assert.equal(longAudit.layouts, 200);
  assert.ok(longAudit.frames > 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await ready();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: new URL('verify-browser__mobile.png', out).pathname.slice(1), fullPage: true });
  for (const candidate of ['a', 'b']) await page.locator(`[data-candidate="${candidate}"] .settings-preview summary`).click();
  await page.screenshot({ path: new URL('verify-browser__settings.png', out).pathname.slice(1), fullPage: true });
  assert.deepEqual(errors, []);
  const report = { passed: true, viewport: '390 × 844', actualDevice: false, errors, workerCount: workers.length, initialParseMs: (await state()).parseMs, taskAudit, longAudit,
    checks: ['真实文本输入及按钮点击', '线程解析、导出、布局', '写回重读语义一致', '错误输入保留及重试', '过期版本取消', '窄屏无页面溢出', '两版静态稿截图'] };
  await writeFile(new URL('verify-browser__report.json', out), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
