import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
const paths = ['index.html', 'manifest.webmanifest', 'icon.svg', ...(await readdir('dist/assets')).map(name => 'assets/' + name)];
const basePath = (process.env.VITE_BASE_PATH ?? '').replace(/^\/+|\/+$/g, '');
const base = basePath ? '/' + basePath + '/' : '/';
const prefix = 'guitar-tabs-' + createHash('sha256').update(base).digest('hex').slice(0, 8) + '-';
const digest = createHash('sha256');
for (const path of paths) digest.update(await readFile(join('dist', path)));
const cache = prefix + digest.digest('hex').slice(0, 12);
const script = `const BASE=${JSON.stringify(base)};const PREFIX=${JSON.stringify(prefix)};const CACHE=${JSON.stringify(cache)};const FILES=${JSON.stringify(paths.map(path => base + path))};
self.addEventListener('install',event=>{event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(FILES)));});
self.addEventListener('activate',event=>{event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith(PREFIX)&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim()));});
self.addEventListener('fetch',event=>{const url=new URL(event.request.url);if(event.request.method!=='GET'||url.origin!==self.location.origin||!url.pathname.startsWith(BASE))return;event.respondWith(caches.open(CACHE).then(async cache=>{const cached=await cache.match(event.request,{ignoreVary:true});if(cached)return cached;try{return await fetch(event.request);}catch(error){if(event.request.mode==='navigate')return await cache.match(BASE+'index.html',{ignoreVary:true});throw error;}}));});
`;
await writeFile('dist/sw.js', script);
console.log(`Offline cache: ${paths.length} files`);
